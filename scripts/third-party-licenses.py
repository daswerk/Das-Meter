LICENSE_FILES = ("license", "licence", "copying", "notice", "copyright", "unlicense")


def metadata(target):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--filter-platform", target],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def shipped_packages(meta):
    """The packages reachable from the shipped binaries through normal deps."""
    by_id = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    workspace = set(meta["workspace_members"])
    start = [p["id"] for p in meta["packages"] if p["name"] in SHIPPED and p["id"] in workspace]
    seen, stack = set(), list(start)
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            # Build scripts and tests don't end up in the binaries.
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    return [by_id[pid] for pid in seen if pid not in workspace]


def license_texts(package):
    """The licence and notice files in the crate's source, by file name."""
    folder = os.path.dirname(package["manifest_path"])
    texts = []
    for name in sorted(os.listdir(folder)):
        path = os.path.join(folder, name)
        if os.path.isfile(path) and name.lower().startswith(LICENSE_FILES):
            with open(path, encoding="utf-8", errors="replace") as f:
                texts.append((name, f.read().strip()))
    if package.get("license_file") and not texts:
        path = os.path.join(folder, package["license_file"])
        if os.path.isfile(path):
            with open(path, encoding="utf-8", errors="replace") as f:
                texts.append((os.path.basename(path), f.read().strip()))
    return texts


def source(package):
    if package.get("repository"):
        return package["repository"]
    if package["source"] and package["source"].startswith("git+"):
        return package["source"][4:].split("#")[0]
    return f"https://crates.io/crates/{package['name']}"


def standard_text(package):
    """For a crate without a licence file: the licence text it's under (the
    Apache-2.0 text where it may be chosen), and what to call it."""
    expression = package.get("license") or ""
    if "Apache-2.0" in expression:
        return "Apache-2.0 (as in this repository's LICENSE-APACHE)", None
    if "MIT" in expression:
        authors = ", ".join(package.get("authors") or []) or f"the {package['name']} authors"
        return "MIT", f"Copyright (c) {authors}\n\n{MIT}"
    if "BSL-1.0" in expression:
        return "BSL-1.0", BSL
    return expression, None


def render(packages):
    packages = sorted(packages, key=lambda p: (p["name"].lower(), p["version"]))
    lines = [
        "# Third-party licences",
        "",
        "Das-Meter (MIT OR Apache-2.0) is built from these crates. Each is listed",
        "with its licence, where its source is, and the licence texts it ships.",
        "The Symphonia crates are MPL-2.0 (ADR 0006): they are used unmodified,",
        "and their source is at the links given.",
        "",
        "Generated by `scripts/third-party-licenses.py`; don't edit by hand.",
        "",
        "| Crate | Version | Licence | Source |",
        "|---|---|---|---|",
    ]
    for p in packages:
        lines.append(
            f"| {p['name']} | {p['version']} | {p.get('license') or 'see below'} | {source(p)} |"
        )
    lines.append("")
    # Identical texts (most Apache-2.0 copies, say) are given once.
    shown = {}
    for p in packages:
        for name, text in license_texts(p):
            shown.setdefault(text, []).append(f"{p['name']} {p['version']} ({name})")
    lines += ["## Licence texts", ""]
    for text, owners in shown.items():
        lines.append("### " + ", ".join(owners))
        lines.append("")
        lines.append("```text")
        lines.append(text.replace("```", "'''"))
        lines.append("```")
        lines.append("")
    missing = [p for p in packages if not license_texts(p)]
    if missing:
        lines += [
            "## Crates without a licence file",
            "",
            "These state their licence only in their manifest. Under the standard text:",
            "",
        ]
        texts = {}
        for p in missing:
            name, text = standard_text(p)
            lines.append(f"- {p['name']} {p['version']} ({p.get('license')}): {name}")
            if text:
                texts.setdefault(text, []).append(f"{p['name']} {p['version']}")
        lines.append("")
        for text, owners in texts.items():
            lines.append("### " + ", ".join(owners))
            lines.append("")
            lines.append("```text")
            lines.append(text)
            lines.append("```")
            lines.append("")
        with open(os.path.join(ROOT, "LICENSE-APACHE"), encoding="utf-8") as f:
            apache = f.read().strip()
        lines += ["### Apache-2.0", "", "```text", apache, "```", ""]
    return "\n".join(lines)


def main():
    packages = {}
    for target in TARGETS:
        for p in shipped_packages(metadata(target)):
            packages[p["id"]] = p
    text = render(list(packages.values()))
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                print("THIRD-PARTY-LICENSES.md is out of date: run scripts/third-party-licenses.py")
                sys.exit(1)
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
